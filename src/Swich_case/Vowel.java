package Swich_case;

public class Vowel {
	public static void main(String[] args) {
		
		char ch = 'e';
		
		switch (ch) {
		case 1 : System.out.println("a");
		break;
		case 2 : System.out.println("e is vowel");
		break;
		case 3 : System.out.println("i");
		break;
		case 4 : System.out.println("o");
		break;
		case 5 : System.out.println("u");
		break;
		default : System.out.println("ch+ is a constant");
		break;
		}
	}

}
